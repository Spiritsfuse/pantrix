#!/usr/bin/env bash
# Exercise terraform plan/apply/destroy against Moto, a local AWS API emulator,
# when no real AWS account is available.
#
#   pip install "moto[server]" && moto_server -H 127.0.0.1 -p 5055 &
#   scripts/terraform/plan-against-emulator.sh [plan|apply|destroy]
#
# IMPORTANT: this does NOT create anything in AWS. It proves the configuration
# resolves, plans a complete resource graph and that the dependency order works.
# The real workflow (terraform/README.md) is unchanged: the emulator endpoints
# live only in a throw-away copy of the directory, never in terraform/.
set -euo pipefail
cd "$(dirname "$0")/../.."
source scripts/lib/term.sh

ACTION="${1:-plan}"
ENDPOINT="${MOTO_ENDPOINT:-http://127.0.0.1:5055}"
WORK="${TF_EMULATOR_DIR:-${TMPDIR:-/tmp}/pantrix-tf-emulator}"

mkdir -p "${WORK}"
cp terraform/*.tf terraform/.terraform.lock.hcl "${WORK}/"
cat > "${WORK}/zz_emulator_override.tf" <<EOF
# Generated by plan-against-emulator.sh - points the provider at Moto (${ENDPOINT}).
provider "aws" {
  region                      = var.region
  access_key                  = "emulator"
  secret_key                  = "emulator"
  skip_credentials_validation = true
  skip_metadata_api_check     = true
  skip_requesting_account_id  = false

  endpoints {
    ec2            = "${ENDPOINT}"
    eks            = "${ENDPOINT}"
    iam            = "${ENDPOINT}"
    kms            = "${ENDPOINT}"
    sts            = "${ENDPOINT}"
    cloudwatchlogs = "${ENDPOINT}"
    ssm            = "${ENDPOINT}"
  }

  default_tags {
    tags = local.tags
  }
}
EOF

# On real AWS the node group looks up the latest EKS AMI release in a public SSM
# parameter under /aws/service/, which Moto does not provide. In the emulator copy
# only, use the AMI type's default release instead of that lookup.
cat >> "${WORK}/zz_emulator_override.tf" <<'EOF'

module "eks" {
  eks_managed_node_groups = {
    general = merge(local.general_node_group, { use_latest_ami_release_version = false })
  }
}
EOF

cd "${WORK}"
note "Terraform working copy: ${WORK} (AWS API emulator at ${ENDPOINT} - NOT a real AWS account)"
run terraform init -input=false -no-color \> /dev/null \&\& echo "terraform init: ok"
case "${ACTION}" in
  plan) run terraform plan -input=false -no-color ;;
  apply) run terraform apply -input=false -no-color -auto-approve ;;
  # -refresh=false: Moto has no DescribeAddonVersions API, which a refresh would call.
  destroy) run terraform destroy -input=false -no-color -auto-approve -refresh=false ;;
  *) echo "usage: $0 plan|apply|destroy" >&2; exit 2 ;;
esac
